import type { App } from "../app";
import { sendSystemAlertToAllSuperusers } from "../mail/system-alert";
import { errorMessage } from "../util";
import { generateBackupName } from "./create";

// Port of PB core/backup.go registerAutobackupHooks.

const JOB_ID = "__hbAutoBackup__";
const AUTO_PREFIX = "@auto_hb_backup_";

async function autoBackup(app: App): Promise<void> {
  const name = generateBackupName(app, AUTO_PREFIX);
  try {
    await app.createBackup(name);
  } catch (err) {
    const error = errorMessage(err);
    app.logger.error("[Backup cron] Failed to create backup", { name, error });
    try {
      await sendSystemAlertToAllSuperusers(
        app,
        "Autobackup failure",
        `Failed to create/upload automated backup. Raw error:\n${error}`,
      );
    } catch (alertErr) {
      app.logger.warn("[Backup cron] Failed to send backup error alerts", {
        name,
        error: errorMessage(alertErr),
      });
    }
  }

  const maxKeep = app.settings.current().backups.cronMaxKeep;
  if (maxKeep === 0) return;
  const fsys = app.newBackupsFilesystem();
  let files;
  try {
    files = await fsys.list(AUTO_PREFIX);
  } catch (err) {
    app.logger.error("[Backup cron] Failed to list autogenerated backups", {
      error: errorMessage(err),
    });
    return;
  }
  if (maxKeep >= files.length) return;
  // newest first; names carry the creation time, so they break mtime ties
  files.sort(
    (a, b) =>
      b.modified.getTime() - a.modified.getTime() ||
      (a.key < b.key ? 1 : a.key > b.key ? -1 : 0),
  );
  for (const f of files.slice(maxKeep)) {
    try {
      await fsys.delete(f.key);
    } catch (err) {
      app.logger.error(
        "[Backup cron] Failed to remove old autogenerated backup",
        {
          key: f.key,
          error: errorMessage(err),
        },
      );
    }
  }
}

export function registerAutoBackup(app: App): void {
  const loadJob = () => {
    const { cron } = app.settings.current().backups;
    if (cron === "") app.scheduler.remove(JOB_ID);
    else app.scheduler.add(JOB_ID, cron, () => autoBackup(app));
  };
  app.onBootstrap(async (e) => {
    await e.next();
    loadJob();
  });
  app.onSettingsReload(async (e) => {
    await e.next();
    loadJob();
  });
}
